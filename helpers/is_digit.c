#include "../push_swap2.h"

int	is_digit(const char *s)
{
	int	i;

	if (!s || !s[0])
		return (0);
	i = 0;
	while (s[i])
	{
		if (!(s[i] >= '0' && s[i] <= '9'))
			break ;
		i++;
	}
	if (s[i] == '\0')
		return (1);
	return (0);
}
