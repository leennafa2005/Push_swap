#include "ft_printf.h"

int	ft_putstr(int fd, char *s)
{
	int	i;

	i = 0;
	if (s == NULL)
		return (write(fd, "(null)", 6));
	while (s[i])
	{
		write(fd, &s[i], 1);
		i++;
	}
	return (i);
}
